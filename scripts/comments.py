#!/usr/bin/env python3
import io
import re
import sys
import tokenize

DIRECTIVE = re.compile(
    r"(?://|/\*|\#|<!--)\s*\#(?:if|elif|else|endif)\b"
    r"|\#\s*shellcheck\s"
    r"|(?://|/\*)\s*(?:<auto-generated|NOLINT|clang-format\s+(?:on|off)|qmllint\s|eslint-|ReSharper\s)"
    r"|\#\s*(?:noqa|type:\s*ignore|pylint:|-\*-)"
)

IDENT = re.compile(r"[A-Za-z_$][\w$]*|\d[\w.]*")
REGEX_KEYWORDS = {"return", "typeof", "case", "do", "else", "in", "instanceof", "new", "delete", "void", "throw", "yield", "await"}


class CLike:
    def __init__(self, src, lang):
        self.s = src
        self.lang = lang
        self.found = []

    def run(self):
        self.code(0, None)
        return self.found

    def line_comment(self, i):
        j = self.s.find("\n", i)
        j = len(self.s) if j < 0 else j
        self.found.append((i, j))
        return j

    def block_comment(self, i):
        j = self.s.find("*/", i + 2)
        j = len(self.s) if j < 0 else j + 2
        self.found.append((i, j))
        return j

    def code(self, i, close):
        s, n = self.s, len(self.s)
        depth = 0
        last = ""
        while i < n:
            c = s[i]
            if s.startswith("//", i):
                i = self.line_comment(i)
                continue
            if s.startswith("/*", i):
                i = self.block_comment(i)
                continue
            if c.isspace():
                i += 1
                continue
            if close is not None:
                if c == "{":
                    depth += 1
                elif c == "}":
                    if depth == 0:
                        return i + 1
                    depth -= 1
            j = self.literal(i, last)
            if j is not None:
                i, last = j, "1"
                continue
            m = IDENT.match(s, i)
            if m:
                i, last = m.end(), m.group()
                continue
            i, last = i + 1, c
        return i

    def literal(self, i, last):
        s, c = self.s, self.s[i]
        if self.lang == "cs":
            m = re.compile(r'([$@]*)("+)').match(s, i)
            if m and (c == '"' or m.group(1)) and not (i and (s[i - 1].isalnum() or s[i - 1] == "_")):
                prefix, quotes = m.group(1), len(m.group(2))
                start = i + len(prefix) + 1
                if "@" in prefix:
                    return self.quoted(start, '"', escape=None, doubled=True, holes="$" in prefix)
                if quotes >= 3:
                    return self.raw(i + len(prefix) + quotes, quotes, prefix.count("$"))
                return self.quoted(start, '"', escape="\\", holes="$" in prefix)
            if c == "'":
                return self.quoted(i + 1, "'", escape="\\")
        elif self.lang == "cpp":
            m = re.compile(r'(?:u8|u|U|L)?R"([^()\\\s]{0,16})\(').match(s, i)
            if m and not (i and (s[i - 1].isalnum() or s[i - 1] == "_")):
                end = ")" + m.group(1) + '"'
                j = s.find(end, m.end())
                return len(s) if j < 0 else j + len(end)
            if c == '"':
                return self.quoted(i + 1, '"', escape="\\")
            if c == "'" and not (last[:1].isdigit() and s[i - 1].isalnum()):
                return self.quoted(i + 1, "'", escape="\\")
        else:
            if c in "'\"":
                return self.quoted(i + 1, c, escape="\\")
            if c == "`":
                return self.template(i + 1)
            if c == "/" and (last == "" or last in "(,=:[!&|?{};+-*%<>~^" or last in REGEX_KEYWORDS):
                return self.regex(i + 1)
        return None

    def raw(self, i, quotes, dollars):
        s, n = self.s, len(self.s)
        while i < n:
            if s.startswith('"' * quotes, i):
                return i + quotes
            if dollars and s[i] == "{":
                run = len(s[i:]) - len(s[i:].lstrip("{"))
                i += run
                if run >= dollars:
                    i = self.code(i, "}")
                    for _ in range(dollars - 1):
                        if s.startswith("}", i):
                            i += 1
            else:
                i += 1
        return n

    def quoted(self, i, quote, escape, doubled=False, holes=False):
        s, n = self.s, len(self.s)
        while i < n:
            c = s[i]
            if escape and c == escape:
                i += 2
            elif c == quote:
                if doubled and s.startswith(quote * 2, i):
                    i += 2
                else:
                    return i + 1
            elif c == "\n" and not doubled:
                return i
            elif holes and c == "{":
                i = i + 2 if s.startswith("{{", i) else self.code(i + 1, "}")
            else:
                i += 1
        return n

    def template(self, i):
        s, n = self.s, len(self.s)
        while i < n:
            if s[i] == "\\":
                i += 2
            elif s[i] == "`":
                return i + 1
            elif s.startswith("${", i):
                i = self.code(i + 2, "}")
            else:
                i += 1
        return n

    def regex(self, i):
        s, n = self.s, len(self.s)
        in_class = False
        while i < n:
            c = s[i]
            if c == "\\":
                i += 2
                continue
            if c == "\n":
                return i
            if c == "[":
                in_class = True
            elif c == "]":
                in_class = False
            elif c == "/" and not in_class:
                m = IDENT.match(s, i + 1)
                return m.end() if m else i + 1
            i += 1
        return n


class Shell:
    HEREDOC = re.compile(r"""<<(-?)[ \t]*((?:'[^'\n]*'|"[^"\n]*"|\\.|[^\s;&|<>()'"])+)""")

    def __init__(self, src):
        self.s = src
        self.found = []
        self.heredocs = []

    def run(self):
        self.code(0, None)
        return self.found

    def code(self, i, close):
        s, n = self.s, len(self.s)
        depth = 0
        while i < n:
            c = s[i]
            if c == "\\":
                i += 2
            elif c == "\n":
                i = self.bodies(i + 1)
            elif c == "#" and (i == 0 or s[i - 1] in " \t\n;&|()"):
                j = s.find("\n", i)
                j = n if j < 0 else j
                self.found.append((i, j))
                i = j
            elif c == "'":
                j = s.find("'", i + 1)
                i = n if j < 0 else j + 1
            elif c == '"':
                i = self.double(i + 1)
            elif s.startswith("$((", i):
                i = self.arithmetic(i + 3)
            elif s.startswith("$(", i):
                i = self.code(i + 2, ")")
            elif c == "`":
                if close == "`":
                    return i + 1
                i = self.code(i + 1, "`")
            elif c == "(":
                depth += 1
                i += 1
            elif c == ")":
                if close == ")" and depth == 0:
                    return i + 1
                depth -= 1
                i += 1
            elif s.startswith("<<", i) and not s.startswith("<<<", i):
                m = self.HEREDOC.match(s, i)
                if m:
                    word = re.sub(r"""'([^']*)'|"([^"]*)"|\\(.)""", lambda q: "".join(g or "" for g in q.groups()), m.group(2))
                    self.heredocs.append((word, m.group(1) == "-"))
                    i = m.end()
                else:
                    i += 2
            else:
                i += 1
        return i

    def arithmetic(self, i):
        s, n = self.s, len(self.s)
        depth = 2
        while i < n and depth:
            depth += {"(": 1, ")": -1}.get(s[i], 0)
            i += 1
        return i

    def double(self, i):
        s, n = self.s, len(self.s)
        while i < n:
            c = s[i]
            if c == "\\":
                i += 2
            elif c == '"':
                return i + 1
            elif s.startswith("$((", i):
                i = self.arithmetic(i + 3)
            elif s.startswith("$(", i):
                i = self.code(i + 2, ")")
            elif c == "`":
                i = self.code(i + 1, "`")
            else:
                i += 1
        return n

    def bodies(self, i):
        s, n = self.s, len(self.s)
        while self.heredocs:
            word, tabs = self.heredocs.pop(0)
            while i < n:
                j = s.find("\n", i)
                j = n if j < 0 else j
                line = s[i:j]
                i = j + 1
                if (line.lstrip("\t") if tabs else line) == word:
                    break
        return i


def python_comments(src):
    starts = [0]
    for line in src.splitlines(keepends=True):
        starts.append(starts[-1] + len(line))
    found = []
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT:
            a = starts[tok.start[0] - 1] + tok.start[1]
            found.append((a, a + len(tok.string)))
    return found


def xml_comments(src):
    return [m.span() for m in re.finditer(r"<!\[CDATA\[.*?\]\]>|<!--.*?-->", src, re.S) if m.group().startswith("<!--")]


def language(path, src):
    name = path.rsplit("/", 1)[-1]
    ext = name.rsplit(".", 1)[-1] if "." in name else ""
    if ext == "cs":
        return lambda: CLike(src, "cs").run()
    if ext in ("cpp", "cc", "c", "h", "hpp"):
        return lambda: CLike(src, "cpp").run()
    if ext in ("qml", "js", "mjs"):
        return lambda: CLike(src, "js").run()
    if ext in ("csproj", "targets", "props"):
        return lambda: xml_comments(src)
    if ext == "py" or re.match(r"#!.*python", src):
        return lambda: python_comments(src)
    if ext in ("sh", "bash") or re.match(r"#!\S*/(?:env )?(?:ba|da)?sh\b", src):
        return lambda: Shell(src).run()
    return None


def comments(path, src):
    find = language(path, src)
    if find is None:
        return []
    found = find()
    if any("<auto-generated" in src[a:b] for a, b in found):
        return []
    return [(a, b) for a, b in found if not (a == 0 and src.startswith("#!")) and not DIRECTIVE.match(src[a:b])]


def join_kept(body, gone):
    kept = ""
    gap = False
    for ch, g in zip(body, gone):
        if g:
            gap = bool(kept)
            continue
        if gap:
            if kept[-1].isspace() and ch.isspace():
                continue
            if not kept[-1].isspace() and not ch.isspace() and kept[-1] not in "([{" and ch not in ")]},;":
                kept += " "
            gap = False
        kept += ch
    return kept


def strip(src, spans):
    gone = bytearray(len(src))
    for a, b in spans:
        gone[a:b] = b"\1" * (b - a)
    out = []
    dropped = False
    pos = 0
    for line in src.splitlines(keepends=True):
        end = pos + len(line)
        if any(gone[pos:end]):
            body = line.rstrip("\r\n")
            kept = join_kept(body, gone[pos : pos + len(body)]).rstrip()
            if not kept.strip():
                dropped = True
                pos = end
                continue
            line = kept + line[len(body):]
        blank = not line.strip()
        if blank and dropped and (not out or not out[-1].strip()):
            pos = end
            continue
        out.append(line)
        dropped = False
        pos = end
    while dropped and out and not out[-1].strip():
        out.pop()
    return "".join(out)


def main(args):
    fix = "--fix" in args
    paths = [a for a in args if a != "--fix"]
    bad = []
    for path in paths:
        with open(path, "rb") as f:
            try:
                src = f.read().decode("utf-8")
            except UnicodeDecodeError:
                continue
        spans = comments(path, src)
        if not spans:
            continue
        if fix:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(strip(src, spans))
            continue
        bad.append(path)
        for a, b in spans:
            line = src.count("\n", 0, a) + 1
            print(f"{path}:{line}: {src[a:b].splitlines()[0]}")
    if bad:
        print("comments: this repo's code has no comments (AGENTS.md). Fix: python3 scripts/comments.py --fix " + " ".join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
